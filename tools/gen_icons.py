"""Writes tests/fixtures/icons.lua: the icon name of every item in LootRuler/Data/Loot.lua, so the test
stand-in for the game can show real item icons in the screen pictures (the game itself has them already).

  python3 tools/gen_icons.py <wowsims/tbc checkout>     (reads assets/item_data/all_item_tooltips.csv)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ids = sorted(set(int(x) for x in re.findall(r'^\s+\[(\d+)\] = \{', open(os.path.join(ROOT, 'LootRuler/Data/Loot.lua')).read(), re.M)))
icons = {}
wanted = set(ids)
# one item a line: id, url, then Wowhead's tooltip JSON (unquoted, so read the icon straight out of the line)
with open(os.path.join(sys.argv[1], 'assets/item_data/all_item_tooltips.csv'), encoding='utf-8', errors='replace') as f:
    for line in f:
        m = re.match(r'(\d+),[^,]*,\{.*?"icon":"([^"]+)"', line)
        if m and int(m.group(1)) in wanted:
            icons[int(m.group(1))] = m.group(2)
lines = ['-- Item icon names for the tests (generated by tools/gen_icons.py from wowsims/tbc\'s Wowhead tooltips).',
         '-- From wowsims/tbc (https://github.com/wowsims/tbc), MIT licence, copyright the wowsims/tbc authors. Not shipped in the addon.',
         'return {']
lines += [f'  [{i}] = "{icons[i]}",' for i in ids if icons.get(i)]
lines.append('}')
open(os.path.join(ROOT, 'tests/fixtures/icons.lua'), 'w').write('\n'.join(lines) + '\n')
print(f'{sum(1 for i in ids if icons.get(i))} of {len(ids)} items have icons')
